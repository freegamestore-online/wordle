#!/usr/bin/env python3
"""Regenerate src/lib/wordlist.ts from public word lists.

Usage: python3 scripts/build-words.py <scowl-final-dir> <enable1.txt>

Sources (download them first):
  SCOWL 2020.12.07, Kevin Atkinson. Permissive licence (see the notice in the output file).
    https://downloads.sourceforge.net/project/wordlist/SCOWL/2020.12.07/scowl-2020.12.07.tar.gz
    Use the extracted `final/` directory.
  ENABLE (Enhanced North American Benchmark Lexicon), public domain.
    https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt

Answers: five-letter words in SCOWL size 40 or less (common English), without simple
plurals / third-person forms / -ed forms of shorter words, minus the BLOCKED list
(offensive, crude, obscure or inflected forms that read badly as an answer).
Valid guesses: answers + ENABLE + SCOWL size 80 or less, minus SLURS.

The answers are written in alphabetical order; the daily order is a seeded shuffle in
words.ts. Changing the answer list changes every future daily word, so do it rarely.
"""
import re
import sys
from pathlib import Path

FIVE = re.compile(r"[a-z]{5}")

BLOCKED = set("""
bitch booby booty booze chink fagot feces gayer horny kinky lusty nuder penis pussy queer
semen sperm whore lynch enema urine harem sissy idiot moron ninny vomit vodka opium fetus
ovary bowel groin bosom buxom coons bimbo fanny fecal fetal gypsy homer mecca potty pubic
pygmy welsh
pends abler apter haler weest dimer edger rifer flied laxer sizer sorta dunno gonna wanna
lemme kinda gimme unsay unman unset upped aping axing cuing eking ruing suing awing octal
halon maria roman uteri genii radii oases ivies sager rawer coyer wryer direr viler huger
muter liker lamer barer baser rarer purer riper odder newsy tatty lorry tonne fiver mamma
nappy fiche filet feted flies fries cries dries tries pries plies shies spies spied pried
plied jeans dregs mumps datum pokey shyer slier icier surer truer bluer freer gotta hokey
reran emcee synod getup pinup cabby payee
""".split())

SLURS = set("kikes spics spick gooks dykes fagot faggy homos nigga niggs".split())


def scowl(final: Path, levels, pattern=FIVE):
    words = set()
    for level in levels:
        for prefix in ("english-words", "american-words"):
            path = final / f"{prefix}.{level}"
            if path.exists():
                for line in path.read_text(encoding="latin-1").split():
                    if pattern.fullmatch(line):
                        words.add(line)
    return words


def main(final_dir: str, enable_path: str) -> None:
    final = Path(final_dir)
    common = scowl(final, [10, 20, 35, 40])
    wide = scowl(final, [10, 20, 35, 40, 50, 55, 60, 70, 80])
    short = scowl(final, [10, 20, 35, 40, 50], re.compile(r"[a-z]{3,4}"))

    def inflected(w: str) -> bool:
        if w.endswith("s") and not w.endswith("ss") and (w[:-1] in short or w[:-1] in wide):
            return True
        if w.endswith("es") and w[:-2] in short:
            return True
        return w.endswith("ed") and (w[:-2] in short or w[:-1] in short)

    answers = sorted(w for w in common if not inflected(w) and w not in BLOCKED)
    enable = {w for w in Path(enable_path).read_text().split() if FIVE.fullmatch(w)}
    guesses = sorted((enable | wide) - set(answers) - SLURS)

    notice = Path(final, "..", "Copyright").resolve().read_text(encoding="latin-1").split("\n\n")[0:3]
    out = Path(__file__).resolve().parent.parent / "src/lib/wordlist.ts"
    out.write_text(
        "// Generated by scripts/build-words.py. Do not edit by hand.\n"
        "//\n"
        "// Word data from SCOWL (http://wordlist.aspell.net/) and ENABLE (public domain).\n"
        "// SCOWL licence notice:\n"
        + "".join(f"//   {line}\n" if line else "//\n" for line in "\n\n".join(notice).splitlines())
        + "\n"
        f"/** {len(answers)} answer words, alphabetical, five letters each with no separator. */\n"
        f'export const ANSWER_DATA =\n  "{"".join(answers)}";\n\n'
        f"/** {len(guesses)} further valid guesses (not answers), alphabetical, packed the same way. */\n"
        f'export const GUESS_DATA =\n  "{"".join(guesses)}";\n'
    )
    print(f"{len(answers)} answers, {len(guesses)} extra guesses, {len(answers) + len(guesses)} valid in all")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
